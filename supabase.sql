where not exists (select 1 from public.drivers);

alter table public.drivers enable row level security;
alter table public.delivery_orders enable row level security;

create policy "public read drivers" on public.drivers for select using (true);
create policy "public insert drivers" on public.drivers for insert with check (true);
create policy "public update drivers" on public.drivers for update using (true) with check (true);
create policy "public delete drivers" on public.drivers for delete using (true);

create policy "public read orders" on public.delivery_orders for select using (true);
create policy "public insert orders" on public.delivery_orders for insert with check (true);
create policy "public update orders" on public.delivery_orders for update using (true) with check (true);
create policy "public delete orders" on public.delivery_orders for delete using (true);

alter publication supabase_realtime add table public.drivers;
alter publication supabase_realtime add table public.delivery_orders;
